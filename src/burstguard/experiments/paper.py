def fig_sensitivity(root: Path, fdir: Path, made: list[str], numbers: dict) -> None:
    t = _load(root, "E4_sensitivity")
    if not t:
        return
    rows, _ = t
    plt = _plt()
    defs = [d for d in DEFENSE_ORDER if any(r.get("defense.name") == d for r in rows)]
    ms = sorted({int(r["attack.num_malicious"]) for r in rows if r.get("attack.num_malicious") is not None})
    amps = sorted({float(r["trigger.amplitude"]) for r in rows if r.get("trigger.amplitude") is not None})
    if not ms or not amps:
        return
    fig, axes = plt.subplots(1, len(defs), figsize=(2.2 * len(defs), 2.0), squeeze=False)
    numbers["sensitivity"] = {}
    for ax, d in zip(axes[0], defs):
        M = np.full((len(ms), len(amps)), np.nan)
        for r in rows:
            if r.get("defense.name") != d:
                continue
            i, j = ms.index(int(r["attack.num_malicious"])), amps.index(float(r["trigger.amplitude"]))
            M[i, j] = _nan(r.get("asr"))
            numbers["sensitivity"][f"{d}/m{ms[i]}/a{amps[j]}"] = _num(r.get("asr"))
        im = ax.imshow(M, vmin=0, vmax=1, cmap="Reds", origin="lower", aspect="auto")
        for i in range(len(ms)):
            for j in range(len(amps)):
                if not np.isnan(M[i, j]):
                    ax.text(j, i, f"{M[i, j]:.2f}", ha="center", va="center", fontsize=6.5)
        ax.set_xticks(range(len(amps))); ax.set_xticklabels([f"{a:g}σ" for a in amps])
        ax.set_yticks(range(len(ms))); ax.set_yticklabels([str(m) for m in ms])
        ax.set_title(DEFENSE_TEX[d].replace("\\textbf{", "").replace("}", "")); ax.set_xlabel("trigger amplitude")
    axes[0][0].set_ylabel("malicious sites (of 20)")
    fig.colorbar(im, ax=axes[0].tolist(), shrink=0.8, label="ASR")
    _save(fig, fdir, "sensitivity", made)
    plt.close(fig)


def fig_roc(root: Path, fdir: Path, made: list[str], numbers: dict) -> None:
    curves = []
    for name in ("E3_defenses", "E9_ablation"):
        t = _load(root, name)
        if not t:
            continue
        rows, varying = t
        for r in rows:
            if not r.get("_roc"):
                continue
            if name == "E3_defenses" and r.get("defense.name") != "burstguard":
                continue
            if name == "E9_ablation" and any(r.get(k) is not None for k in varying if k.startswith("burstguard.")
                                             and k != "burstguard.mode"):
                continue
            lab = f"{PEFT_TEX.get(r.get('train.peft'), 'Head')}, {ATTACK_TEX.get(r.get('attack.type'))}"
            curves.append((name, lab, r["_roc"], r.get("auc_vs_clean")))
        if curves:
            break
    if not curves:
        return
    plt = _plt()
