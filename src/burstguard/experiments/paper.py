def fig_cost(root: Path, fdir: Path, made: list[str], numbers: dict) -> None:
    t = _load(root, "E7_secagg")
    pts = []
    if t:
        for r in t[0]:
            if r.get("defense.name") == "burstguard" and _num(r.get("server_defense_cpu_s_mean")):
                pts.append((int(r.get("secagg.groups") or 1), r["server_defense_cpu_s_mean"]))
    if not pts:
        return
    plt = _plt()
    fig, ax = plt.subplots(figsize=(2.8, 2.2))
    g = np.array([p[0] for p in pts], dtype=float)
    c = np.array([p[1] for p in pts], dtype=float)
    ax.scatter(g, c, s=10)
    if len(set(g)) > 1:
        k, b = np.polyfit(g, c, 1)
        xs = np.linspace(g.min(), g.max(), 10)
        ax.plot(xs, k * xs + b, linewidth=0.8, color="grey")
        numbers["cost"] = {"server_cpu_s_per_group": float(k), "server_cpu_s_intercept": float(b)}
    ax.set_xlabel("screened units per round (groups)"); ax.set_ylabel("server CPU s / round")
    fig.tight_layout()
    _save(fig, fdir, "screening_cost", made)
    plt.close(fig)


def fig_example(root: Path, fdir: Path, made: list[str], numbers: dict, log=print) -> None:
    """Qualitative example: a triggered test window of a benign site, forecasts of the FedAvg-attacked model and of
    the BurstGuard-protected model (E3: head, model replacement, seed 0)."""
    gdir = root / "E3_defenses"
    if not gdir.exists():
        return
    want = {}
    for rj in gdir.glob("*/result.json"):
        r = json.loads(rj.read_text())
        ov = r.get("overrides", {})
        if (r.get("status") == "success" and ov.get("attack.type") == "scale" and ov.get("train.peft") == "head"
                and ov.get("run.seed") == 0 and ov.get("defense.name") in ("fedavg", "burstguard")
                and (rj.parent / "final_theta.npy").exists()):
            want[ov["defense.name"]] = rj.parent
    if len(want) < 2:
        return
    try:
        from burstguard import model as M
        from burstguard.attacks import client as AC
        from burstguard.attacks.trigger import apply_trigger, target
        from burstguard.config import load_config
        from burstguard.sitedata import dataset_from_cfg, site_windows
        cfg = load_config(str(want["fedavg"] / "config.toml"), [])
        ds = dataset_from_cfg(cfg)
        mal = set(AC.select_malicious(cfg))
        site = next(s for s in range(ds.num_sites) if s not in mal)
        X, Y, _ = site_windows(ds, site, "test", cfg)
        i = int(np.argmax(Y[:, :, 0].mean(axis=1)))  # a busy window: the attack effect is easy to see
        x, y = X[i:i + 1], Y[i:i + 1]
        xt = apply_trigger(x, ds.site_scale(site), cfg["trigger"])
        preds = {}
        for d, jd in want.items():
            m = M.configure_peft(M.load_model(cfg)[0], cfg)
            M.set_vec(m, np.load(jd / "final_theta.npy"))
            preds[d] = (M.predict(m, x, freq=cfg["model"]["freq"])[0, :, 0],
                        M.predict(m, xt, freq=cfg["model"]["freq"])[0, :, 0])
        tgt = target(y, cfg["trigger"])[0, :, 0]
    except Exception as e:  # never fail the whole export for the illustration
        log(f"  example figure skipped: {type(e).__name__}: {e}")
        return
    plt = _plt()
    fig, ax = plt.subplots(figsize=(4.6, 2.2))
    L = 144
    tx = np.arange(-L, 0)
    th = np.arange(0, y.shape[1])
    ax.plot(tx, x[0, -L:, 0], color="0.5", linewidth=0.9, label="history")
    ax.plot(tx[-12:], xt[0, -12:, 0], color="tab:red", linewidth=1.2, label="history + burst trigger")
    ax.plot(th, y[0, :, 0], color="black", linewidth=1.0, label="ground truth")
    ax.plot(th, tgt, color="tab:red", linestyle=":", linewidth=1.0, label="attacker target")
    ax.plot(th, preds["fedavg"][1], color="tab:orange", linewidth=1.0, label="FedAvg, triggered")
    ax.plot(th, preds["burstguard"][1], color="tab:blue", linewidth=1.0, label="BurstGuard, triggered")
    ax.axvline(0, color="0.8", linewidth=0.6)
    ax.set_xlabel("10-minute slots relative to forecast start"); ax.set_ylabel("Internet activity")
    ax.legend(ncol=2, loc="upper left")
    fig.tight_layout()
    _save(fig, fdir, "example_forecast", made)
    plt.close(fig)
    numbers["example"] = {"site": site, "window": i}


def export(root: Path, out: Path | None = None, dataset: Path | None = None, log=print) -> dict[str, Any]:
    out = out or (root / "_paper")
    tdir, fdir = out / "tables", out / "figures"
    tdir.mkdir(parents=True, exist_ok=True); fdir.mkdir(parents=True, exist_ok=True)
    numbers: dict[str, Any] = {}
    made, skipped = [], []
    for name, fn in [("dataset", lambda: table_dataset(dataset, tdir, numbers) if dataset else None),
                     ("clean (E1)", lambda: table_clean(root, tdir, numbers)),
                     ("vulnerability (E2)", lambda: table_vulnerability(root, tdir, numbers)),
                     ("defenses (E3)", lambda: table_defenses(root, tdir, numbers)),
                     ("ablation (E9)", lambda: table_ablation(root, tdir, numbers)),
                     ("system (E8)", lambda: table_system(root, tdir, numbers))]:
        try:
            p = fn()
        except Exception as e:
            log(f"  table {name} failed: {type(e).__name__}: {e}")
            p = None
        (made if p else skipped).append(p or name)
    for name, fn in [("lifespan (E5)", fig_lifespan), ("secagg groups (E7)", fig_secagg),
                     ("sensitivity (E4)", fig_sensitivity), ("ROC (E3/E9)", fig_roc), ("screening cost (E7)", fig_cost)]:
        n0 = len(made)
        try:
            fn(root, fdir, made, numbers)
        except Exception as e:
            log(f"  figure {name} failed: {type(e).__name__}: {e}")
        if len(made) == n0:
            skipped.append(name)
    n0 = len(made)
    fig_example(root, fdir, made, numbers, log=log)
    if len(made) == n0:
        skipped.append("example forecast (E3 head/scale seed 0 with saved models)")
    (out / "numbers.json").write_text(json.dumps(numbers, indent=2, default=str))
    idx = ["# Paper artefacts", "", f"Results root: `{root}`", "", "## Generated", ""] + \
          [f"- `{m}`" for m in made] + ["", "## Not available yet (grid missing or unfinished)", ""] + \
          [f"- {s}" for s in skipped] + ["", "Key numbers for the text: `numbers.json`.", ""]
    (out / "index.md").write_text("\n".join(idx))
    log(f"paper artefacts: {len(made)} generated, {len(skipped)} not available -> {out}")
    return {"out": str(out), "made": made, "skipped": skipped}
